"""The Brain: a text-in / text-out box.

THE core abstraction of this project. An agent sits in front of a model and does all
the clever orchestration (memory, protocols, tools, the loop). To the agent, ANY model
— a scripted mock, a tiny local llama, or a huge cloud Gemini — is nothing more than a
function that turns a list of messages into a string of text.

So swapping the brain never changes agent code. That swapability is a lesson in itself.
"""

import json
import os
import time
import urllib.error
import urllib.request
from dataclasses import dataclass

from .tokens import estimate_tokens


@dataclass
class Message:
    """One turn in the conversation the brain sees.

    role is one of:
      "system"    — standing instructions from us to the model (never generated by the model)
      "user"      — the task, and later each tool Observation (we put it in the user role)
      "assistant" — the model's own output (thoughts, actions, final answers)
    """

    role: str
    content: str

    def render(self) -> str:
        return f"<{self.role}> {self.content}"


@dataclass
class Completion:
    """The brain's answer: the generated text plus a bit of bookkeeping."""

    text: str
    model: str
    prompt_tokens: int = 0   # input tokens we sent (estimated)
    completion_tokens: int = 0  # output tokens it generated (estimated)


class Brain:
    """Base class: a text-in / text-out box. Subclass and implement complete()."""

    name = "brain"

    def complete(self, messages: list[Message], **params) -> Completion:
        raise NotImplementedError(f"{type(self).__name__} must implement complete()")

    def describe(self) -> str:
        return f"{type(self).__name__}(model={self.name!r})"


class MockBrain(Brain):
    """Deterministic stand-in for a real model. No network, no pip dependencies.

    Two ways to use it:
      * With a `script` (list of strings), it returns scripted replies one per call.
        This lets us test the AGENT logic (not the model) with perfect reproducibility
        — the basis of the 'golden trace' tests in Milestone 5.
      * Without a script, it returns `default` every time.
    """

    name = "mock"

    def __init__(self, script: list[str] | None = None, default: str | None = None,
                 model: str = "mock-1"):
        self._script = list(script) if script else []
        self._default = default or (
            "Hello! I am a mock model — a stand-in with no real intelligence inside, "
            "so the agent logic can be exercised offline, deterministically, forever."
        )
        self.model = model
        self.call_count = 0
        self.last_params: dict | None = None  # what the agent asked for, for inspection

    def complete(self, messages: list[Message], **params) -> Completion:
        self.call_count += 1
        self.last_params = params
        text = self._script.pop(0) if self._script else self._default
        prompt_tokens = sum(estimate_tokens(m.content) for m in messages)
        return Completion(
            text=text,
            model=self.model,
            prompt_tokens=prompt_tokens,
            completion_tokens=estimate_tokens(text),
        )

    def describe(self) -> str:
        return f"MockBrain(model={self.model!r}, script_steps_left={len(self._script)})"


DEFAULT_OLLAMA_HOST = "http://localhost:11434"


class OllamaUnavailable(RuntimeError):
    """Ollama could not be reached or answered with an HTTP error.

    The name keeps the cause honest: the SERVER (or the hop to it) failed —
    the model itself never got to speak. Carrying guidance in the message
    turns a raw exception into a note a beginner can act on.
    """


class OllamaBrain(Brain):
    """The brain zoo's first REAL member (M7): a local model via Ollama.

    Text-in / text-out exactly like MockBrain — same seam (complete()),
    same agent, zero agent-code changes. Swapping them IS the lesson.

    Talks to `/api/chat` with stdlib urllib only (ZERO pip deps). Decisions
    pinned at M7.0 (PLAN.md):
      * `/api/chat` — message-list in, text out (matches Message -> Completion)
      * `think: True` — ORIGINAL M7.0 pin was False for speed, but the live exam
        (M7.3) falsified it: lfm3 is thinking-native, and with a multi-turn agent
        context think=False produced EMPTY content. Ollama answers thinking in a
        SEPARATE field (message.thinking), so content stays a clean ReAct letter
        anyway — thinking on costs tokens but costs nothing in parsing purity.
        *(Amended 2026-11-02 — the point where a reality check changed the plan.)*
      * long timeout + 1 gentle retry: local inference is slow and a blip
        should not kill a run; `num_predict` caps runaway generations

    The network call sits behind an injectable `transport` function, so all
    conversation-shaping and failure policy can be tested OFFLINE with a fake
    transport — instant, deterministic, no Ollama required. Only one small
    live smoke test touches the real server, and it skips when Ollama is down.
    """

    name = "ollama"

    def __init__(self, model: str = "lfm3:latest", host: str = DEFAULT_OLLAMA_HOST, *,
                 think: bool = True, num_predict: int = 512,
                 temperature: float | None = None,
                 timeout: float = 120.0, retries: int = 1, retry_wait: float = 1.0,
                 transport=None):
        self.model = model
        self.host = host.rstrip("/")
        self.think = think
        self.num_predict = num_predict
        self.temperature = temperature
        self.timeout = timeout
        self.retries = retries
        self.retry_wait = retry_wait
        self._transport = transport or self._default_transport
        self.call_count = 0  # mirrors MockBrain: same knobs for bench parity (M7.4)
        self.total_eval_count = 0          # REAL output tokens, summed by Ollama
        self.total_eval_duration = 0.0     # seconds spent generating (Ollama's clock)
        self.last_payload: dict | None = None  # last request body, for inspection

    # -- the seam the tests swap ---------------------------------------------
    @staticmethod
    def _default_transport(url: str, payload: dict, timeout: float) -> tuple:
        """The ONLY network code in the whole brain: one urllib POST."""
        body = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(
            url, data=body, headers={"Content-Type": "application/json"})
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return resp.status, json.loads(resp.read().decode("utf-8"))

    # -- request shaping: our Message -> Ollama /api/chat --------------------
    def _build_payload(self, messages: list[Message], model: str, think: bool,
                       num_predict: int, temperature: float | None) -> dict:
        options = {"num_predict": num_predict}
        if temperature is not None:
            options["temperature"] = temperature
        return {
            "model": model,
            "messages": [
                # Ollama's chat roles are exactly ours: system / user / assistant.
                # NOTE: we send m.content, NOT m.render() — the "<role>" prefix is
                # OUR textual narration format; a native chat API carries the
                # role in its own JSON field instead.
                {"role": m.role, "content": m.content} for m in messages
            ],
            "stream": False,  # one complete letter, not a token faucet
            "think": think,   # amended M7.0: thinking-native lfm3 goes MUTE under False
            "options": options,
        }

    def complete(self, messages: list[Message], **params) -> Completion:
        """Ask Ollama /api/chat and map the reply into a Completion."""
        allowed = ("model", "think", "num_predict", "temperature")
        unknown = set(params) - set(allowed)
        if unknown:
            raise ValueError(
                f"unknown param(s) {sorted(unknown)} — allowed: {list(allowed)}")
        payload = self._build_payload(
            messages,
            model=params.get("model", self.model),
            think=params.get("think", self.think),
            num_predict=params.get("num_predict", self.num_predict),
            temperature=params.get("temperature", self.temperature),
        )
        url = f"{self.host}/api/chat"
        attempts = self.retries + 1
        last_err: Exception | None = None
        for attempt in range(1, attempts + 1):
            self.call_count += 1  # counts transport attempts: bench needs honesty too
            self.last_payload = payload
            try:
                _, body = self._transport(url, payload, self.timeout)
            # The server SPOKE an error (bad request, model missing...): retrying
            # cannot heal a 4xx — surface it immediately, guidance attached.
            except urllib.error.HTTPError as e:
                raise OllamaUnavailable(
                    f"Ollama answered HTTP {e.code} ({e.reason}) for {self.model!r} "
                    f"— is the model pulled and Ollama >= the required version?") from e
            # No answer at all (refused connection, timeout, malformed body):
            # fail-soft — this MIGHT be a blip, so retry once if allowed.
            except (urllib.error.URLError, OSError, json.JSONDecodeError) as e:
                last_err = e
                if attempt < attempts and self.retry_wait > 0:
                    time.sleep(self.retry_wait)
                continue
            self._note_throughput(body)
            return self._to_completion(body, messages)
        raise OllamaUnavailable(
            f"could not reach Ollama at {self.host} after {attempts} attempt(s) "
            f"({last_err!r}) — is `ollama serve` running, and is the model in "
            f"`ollama list`?") from last_err

    def _note_throughput(self, body: dict) -> None:
        """Aggregate Ollama's own generation counters across the whole run.

        bench needs tok/s measured by the HARDWARE's clock, not a stopwatch
        around agent.run (which would include Python overhead). Ollama reports
        eval_count (generated tokens) and eval_duration (nanoseconds).
        """
        if body.get("eval_count") and body.get("eval_duration"):
            self.total_eval_count += body["eval_count"]
            self.total_eval_duration += body["eval_duration"] / 1e9

    # -- response mapping: Ollama JSON -> Completion --------------------------
    @staticmethod
    def _to_completion(body: dict, messages: list[Message]) -> Completion:
        text = (body.get("message") or {}).get("content", "")
        return Completion(
            text=text,
            model=body.get("model", "ollama"),
            # Ollama reports REAL token counts when it can; when a server omits
            # them we fall back to OUR estimator (MockBrain does the same), so
            # bench numbers never silently sit at zero.
            prompt_tokens=body.get("prompt_eval_count")
            or sum(estimate_tokens(m.content) for m in messages),
            completion_tokens=body.get("eval_count") or estimate_tokens(text),
        )

    def describe(self) -> str:
        return (f"OllamaBrain(model={self.model!r}, host={self.host!r}, "
                f"think={self.think}, num_predict={self.num_predict})")


DEFAULT_GEMINI_HOST = "https://generativelanguage.googleapis.com"


class GeminiUnavailable(RuntimeError):
    """Google's API could not be reached, refused us, or we lack a key.

    Same contract as OllamaUnavailable: the failure carries guidance a
    beginner can act on. It NEVER interpolates the API key (M8.0 credential
    rules): the key rides in a header and never enters a message or URL.
    """


class GeminiBrain(Brain):
    """The brain zoo's first CLOUD member (M8): Gemini via Google's free tier.

    Same text-in/text-out seam as MockBrain/OllamaBrain — same complete(),
    same Completion, zero agent-code changes. Third JSON dialect so far:
      * our "system" message -> Gemini's SEPARATE `systemInstruction` field
      * Message list -> `contents[]` with roles "user" / "model"
        (Gemini has no "system" role inside contents and no "assistant";
        the <role> render() prefix is OUR narration and is NOT sent)
      * thinking: pinned OFF for ReAct at M8.0 (`thinkingBudget: 0`) —
        the M7.0 lesson: an honest default, amendable by reality
      * failure policy: transient errors get 1 gentle retry; HTTP errors are
        surfaced immediately (a 4xx won't heal) with the key NEVER in them

    Credential rules (M8.0), enforced here in code:
      * key from the GEMINI_API_KEY env var (or explicit api_key= param)
      * key sent ONLY in the x-goog-api-key HEADER — never a URL query
        parameter, so no log, trace, or error can capture it
      * no payload recorded in self.last_payload contains the key either
    """

    name = "gemini"

    def __init__(self, model: str = "gemini-3.5-flash-lite",
                 host: str = DEFAULT_GEMINI_HOST, *,
                 api_key: str | None = None, api_key_env: str = "GEMINI_API_KEY",
                 thinking: bool = False, max_output_tokens: int = 512,
                 timeout: float = 120.0, retries: int = 1, retry_wait: float = 1.0,
                 transport=None):
        self.model = model
        self.host = host.rstrip("/")
        self._api_key = api_key
        self._api_key_env = api_key_env
        self.thinking = thinking
        self.max_output_tokens = max_output_tokens
        self.timeout = timeout
        self.retries = retries
        self.retry_wait = retry_wait
        self._transport = transport or self._default_transport
        self.call_count = 0   # transport calls: bench parity with the other brains
        self.total_output_tokens = 0  # REAL counts from usageMetadata, aggregated
        self.last_payload: dict | None = None  # for inspection: NEVER holds the key

    # -- the seam the tests swap ---------------------------------------------
    def _default_transport(self, url: str, payload: dict, timeout: float) -> tuple:
        """The only network code in the brain: one urllib POST with the key in
        the header (M8.0: never a query parameter)."""
        body = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(url, data=body, headers={
            "Content-Type": "application/json",
            "x-goog-api-key": self._resolve_api_key(),
        })
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return resp.status, json.loads(resp.read().decode("utf-8"))

    def _resolve_api_key(self) -> str:
        """Find the key or fail with guidance that names the missing thing."""
        if self._api_key:
            return self._api_key
        key = os.environ.get(self._api_key_env, "")
        if key:
            return key
        raise GeminiUnavailable(
            f"no API key found (looked for env var {self._api_key_env!r}) — export "
            f"GEMINI_API_KEY before starting the session, or pass api_key=; "
            f"credential rules M8.0: never hardcode, never commit")

    # -- request shaping: our Message -> Gemini generateContent ---------------
    def _build_payload(self, messages: list[Message], thinking: bool,
                       max_output_tokens: int) -> dict:
        system_parts: list[str] = []
        contents = []
        for m in messages:
            if m.role == "system":
                system_parts.append(m.content)  # standing rules -> its own field
            else:
                contents.append({
                    # Gemini's chat roles: "user" / "model" — our "assistant"
                    # maps to "model" (third dialect, same role-in-field lesson)
                    "role": {"user": "user", "assistant": "model"}[m.role],
                    "parts": [{"text": m.content}],
                })
        generation_config: dict = {"maxOutputTokens": max_output_tokens}
        # M8.2 LIVE AMENDMENT of the M8.0 think-off pin: this model REJECTS
        # thinkingConfig.thinkingBudget=0 with 400 INVALID_ARGUMENT (bisected
        # one-variable-at-a-time, see PLAN). So we never send thinkingConfig:
        # thinking stays a model default, thought parts are FILTERED by
        # _to_completion — the separate-channel contract still holds.
        payload: dict = {"contents": contents, "generationConfig": generation_config}
        if system_parts:
            payload["systemInstruction"] = {"parts": [{"text": "\n\n".join(system_parts)}]}
        return payload

    def complete(self, messages: list[Message], **params) -> Completion:
        """Ask Gemini generateContent and map the reply into a Completion."""
        allowed = ("model", "thinking", "max_output_tokens")
        unknown = set(params) - set(allowed)
        if unknown:
            raise ValueError(
                f"unknown param(s) {sorted(unknown)} — allowed: {list(allowed)}")
        payload = self._build_payload(
            messages,
            thinking=params.get("thinking", self.thinking),
            max_output_tokens=params.get("max_output_tokens", self.max_output_tokens),
        )
        model = params.get("model", self.model)
        url = f"{self.host}/v1beta/models/{model}:generateContent"
        attempts = self.retries + 1
        last_err: Exception | None = None
        for attempt in range(1, attempts + 1):
            self.call_count += 1
            self.last_payload = payload
            try:
                _, body = self._transport(url, payload, self.timeout)
            # The server SPOKE (400 bad model, 403 bad key, 429 too fast,..):
            # surfacing immediately with code+reason — and NO key material.
            except urllib.error.HTTPError as e:
                raise GeminiUnavailable(
                    f"Gemini answered HTTP {e.code} ({e.reason}) for {self.model!r} "
                    f"— check the model tag, the key's restrictions, and the rate limit") from e
            # No answer at all: fail-soft — one gentle retry.
            except (urllib.error.URLError, OSError, json.JSONDecodeError) as e:
                last_err = e
                if attempt < attempts and self.retry_wait > 0:
                    time.sleep(self.retry_wait)
                continue
            self._note_usage(body)
            return self._to_completion(body, messages)
        raise GeminiUnavailable(
            f"could not reach Google's API at {self.host} after {attempts} attempt(s) "
            f"({last_err!r}) — check the network") from last_err

    # -- response mapping: Gemini JSON -> Completion --------------------------
    @staticmethod
    def _to_completion(body: dict, messages: list[Message]) -> Completion:
        parts = (((body.get("candidates") or [{}])[0]).get("content") or {}).get("parts") or []
        # Thought parts (present only when thinking is enabled) never enter the
        # letter we parse — same separate-channel contract as Ollama's thinking.
        text = "".join(p.get("text", "") for p in parts if not p.get("thought"))
        usage = body.get("usageMetadata") or {}
        return Completion(
            text=text,
            model=body.get("modelVersion") or "gemini",
            # REAL token counts when Google reports them; our estimator as the
            # fallback, mirroring OllamaBrain (bench numbers never sit at 0).
            prompt_tokens=usage.get("promptTokenCount")
            or sum(estimate_tokens(m.content) for m in messages),
            completion_tokens=usage.get("candidatesTokenCount") or estimate_tokens(text),
        )

    def _note_usage(self, body: dict) -> None:
        usage = body.get("usageMetadata") or {}
        if usage.get("candidatesTokenCount"):
            self.total_output_tokens += usage["candidatesTokenCount"]

    def describe(self) -> str:
        return (f"GeminiBrain(model={self.model!r}, host={self.host!r}, "
                f"thinking={self.thinking}, max_output_tokens={self.max_output_tokens}, "
                f"key=<set via env, never displayed>)")