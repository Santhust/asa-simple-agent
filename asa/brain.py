"""The Brain: a text-in / text-out box.

THE core abstraction of this project. An agent sits in front of a model and does all
the clever orchestration (memory, protocols, tools, the loop). To the agent, ANY model
— a scripted mock, a tiny local llama, or a huge cloud Gemini — is nothing more than a
function that turns a list of messages into a string of text.

So swapping the brain never changes agent code. That swapability is a lesson in itself.
"""

from dataclasses import dataclass

from .tokens import estimate_tokens


@dataclass
class Message:
    """One turn in the conversation the brain sees.

    role is one of:
      "system"    — standing instructions from us to the model (never generated by the model)
      "user"      — the task, and later each tool Observation (we put it in the user role)
      "assistant" — the model's own output (thoughts, actions, final answers)
    """

    role: str
    content: str

    def render(self) -> str:
        return f"<{self.role}> {self.content}"


@dataclass
class Completion:
    """The brain's answer: the generated text plus a bit of bookkeeping."""

    text: str
    model: str
    prompt_tokens: int = 0   # input tokens we sent (estimated)
    completion_tokens: int = 0  # output tokens it generated (estimated)


class Brain:
    """Base class: a text-in / text-out box. Subclass and implement complete()."""

    name = "brain"

    def complete(self, messages: list[Message], **params) -> Completion:
        raise NotImplementedError(f"{type(self).__name__} must implement complete()")

    def describe(self) -> str:
        return f"{type(self).__name__}(model={self.name!r})"


class MockBrain(Brain):
    """Deterministic stand-in for a real model. No network, no pip dependencies.

    Two ways to use it:
      * With a `script` (list of strings), it returns scripted replies one per call.
        This lets us test the AGENT logic (not the model) with perfect reproducibility
        — the basis of the 'golden trace' tests in Milestone 5.
      * Without a script, it returns `default` every time.
    """

    name = "mock"

    def __init__(self, script: list[str] | None = None, default: str | None = None,
                 model: str = "mock-1"):
        self._script = list(script) if script else []
        self._default = default or (
            "Hello! I am a mock model — a stand-in with no real intelligence inside, "
            "so the agent logic can be exercised offline, deterministically, forever."
        )
        self.model = model
        self.call_count = 0
        self.last_params: dict | None = None  # what the agent asked for, for inspection

    def complete(self, messages: list[Message], **params) -> Completion:
        self.call_count += 1
        self.last_params = params
        text = self._script.pop(0) if self._script else self._default
        prompt_tokens = sum(estimate_tokens(m.content) for m in messages)
        return Completion(
            text=text,
            model=self.model,
            prompt_tokens=prompt_tokens,
            completion_tokens=estimate_tokens(text),
        )

    def describe(self) -> str:
        return f"MockBrain(model={self.model!r}, script_steps_left={len(self._script)})"